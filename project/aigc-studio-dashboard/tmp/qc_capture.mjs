import { chromium } from "playwright";
const app = "C:/Users/uroborus/project/ember-frame/project/aigc-studio-dashboard";
const browser = await chromium.launch({ channel: "chrome", headless: true });
const page = await browser.newPage({ viewport: { width: 1000, height: 620 }, deviceScaleFactor: 1 });
const errors = [];
page.on("pageerror", (error) => errors.push(error.message));
page.on("console", (message) => { if (message.type() === "error") errors.push(message.text()); });
await page.goto(`http://127.0.0.1:5174/?qc=${Date.now()}`, { waitUntil: "networkidle" });
await page.locator(".three-action").waitFor({ timeout: 10000 });
console.log("button", await page.locator(".three-action").innerText());
console.log("status", await page.locator(".three-status").innerText());
await page.locator(".art25d-scene").screenshot({ path: `${app}/tmp/qc4_initial.png` });
await page.locator(".three-action").click();
await page.waitForTimeout(900);
await page.locator(".art25d-scene").screenshot({ path: `${app}/tmp/qc4_stand_mid.png` });
await page.waitForTimeout(1300);
await page.locator(".art25d-scene").screenshot({ path: `${app}/tmp/qc4_walk_out.png` });
await page.waitForTimeout(2400);
await page.locator(".art25d-scene").screenshot({ path: `${app}/tmp/qc4_idle_out.png` });
await page.locator(".three-action").click();
await page.waitForTimeout(900);
await page.locator(".art25d-scene").screenshot({ path: `${app}/tmp/qc4_walk_back.png` });
await page.waitForTimeout(1600);
await page.locator(".art25d-scene").screenshot({ path: `${app}/tmp/qc4_sit_mid.png` });
await page.waitForTimeout(1600);
await page.locator(".art25d-scene").screenshot({ path: `${app}/tmp/qc4_return_seated.png` });
await browser.close();
console.log(JSON.stringify({ ok: true, errors }));
